/**
 * ASTRAVERSA Ω — Astronomical Provenance Architecture
 *
 * Establishes strict epistemic demarcation between ground-truth observed
 * astronomical objects and computational/procedural simulations.
 *
 * Principles:
 * - OBSERVED: Directly measured by human/spacecraft instruments (NASA, ESA, ESO, etc.)
 * - DERIVED_FROM_OBSERVATIONS: Reconstructed or calculated from observational constraints
 * - PROCEDURAL_SIMULATION: Deterministic or stochastic synthetic entities
 * - HYPOTHETICAL: Theoretical thought-experiments or speculative constructs
 *
 * Never mix or silently conflate observed astronomy with procedural generation.
 */

export const AstronomicalProvenance = {
  /** Directly observed astronomical body confirmed by astronomical instruments */
  OBSERVED: 'OBSERVED',

  /** Modeled, reconstructed, or inferred from observational data sets */
  DERIVED_FROM_OBSERVATIONS: 'DERIVED_FROM_OBSERVATIONS',

  /** Generated by calibrated empirical or theoretical computational models */
  MODEL_BASED: 'MODEL_BASED',

  /** Generated by deterministic or stochastic procedural simulation */
  PROCEDURAL_SIMULATION: 'PROCEDURAL_SIMULATION',

  /** Theoretical, speculative, or unverified astronomical entity */
  HYPOTHETICAL: 'HYPOTHETICAL',
} as const;

export type AstronomicalProvenance =
  (typeof AstronomicalProvenance)[keyof typeof AstronomicalProvenance];

/**
 * Detailed provenance metadata attached to any astronomical entity.
 */
export interface ProvenanceRecord {
  /** Provenance epistemic classification */
  classification: AstronomicalProvenance;

  /** Primary astronomical archive or data mission (e.g. NASA PDS, JPL Horizons, ESA Gaia DR3) */
  sourceArchive?: string;

  /** Formal scientific citation or DOI */
  citation?: string;

  /** Standard astronomical catalog identifier (e.g. "Sol", "Gaia DR3 5853...", "HD 209458", "Kepler-186f") */
  catalogId?: string;

  /** Observational or model confidence score in [0.0, 1.0] */
  confidence?: number;

  /** Measurement epoch or mission date (e.g. "J2000.0", "2024-01-01") */
  epoch?: string;

  /** Descriptive notes regarding observational constraints or instruments used */
  notes?: string;
}

/**
 * Helper to construct a standard ProvenanceRecord for observed astronomical entities.
 */
export function createObservedProvenance(
  catalogId: string,
  sourceArchive: string,
  citation?: string,
  notes?: string
): ProvenanceRecord {
  return {
    classification: AstronomicalProvenance.OBSERVED,
    catalogId,
    sourceArchive,
    citation,
    confidence: 1.0,
    epoch: 'J2000.0',
    notes,
  };
}

/**
 * Helper to construct a standard ProvenanceRecord for derived astronomical entities.
 */
export function createDerivedProvenance(
  catalogId: string,
  sourceArchive: string,
  citation?: string,
  notes?: string
): ProvenanceRecord {
  return {
    classification: AstronomicalProvenance.DERIVED_FROM_OBSERVATIONS,
    catalogId,
    sourceArchive,
    citation,
    confidence: 0.95,
    notes,
  };
}

/**
 * Helper to construct a standard ProvenanceRecord for model-based astronomical entities.
 */
export function createModelProvenance(
  catalogId: string,
  sourceArchive: string,
  citation?: string,
  notes?: string
): ProvenanceRecord {
  return {
    classification: AstronomicalProvenance.MODEL_BASED,
    catalogId,
    sourceArchive,
    citation,
    confidence: 0.9,
    notes,
  };
}

/**
 * Helper to construct a standard ProvenanceRecord for procedural simulation entities.
 */
export function createProceduralProvenance(
  seed: number,
  notes?: string
): ProvenanceRecord {
  return {
    classification: AstronomicalProvenance.PROCEDURAL_SIMULATION,
    catalogId: `PROC-${seed}`,
    sourceArchive: 'ASTRAVERSA Procedural Engine',
    confidence: 1.0,
    notes: notes ?? 'Generated deterministically via SeededRandom',
  };
}

